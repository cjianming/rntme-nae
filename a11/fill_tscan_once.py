# -*- coding: utf-8 -*-
"""把迭代预算扫描的实测结果回填进 paper.md 的 TSCAN 占位。"""
p = "paper.md"
s = open(p, encoding="utf-8").read()
txt = (
    "为检验这一推断，在公开集 64 px、$M=2$ 的缩减配置上逐档实测（$T$=5、8、11、15）："
    "扰动的最大分量在 $T=5$ 时尚未触界（饱和比例 0%），$T=8$ 起达 100%；"
    "未见目标上的成功率依次为 46.7%、56.7%、56.7%、56.7%，"
    "$L_2$ 扰动依次为 4.00、6.20、6.22、6.21，单样本耗时由 1.30 s 增至 2.11 s。"
    "也就是说，一旦幅度饱和，继续迭代既不增大扰动也不提高成功率，只增加开销。"
    "这与本节开头“$T$ 由 10 增至 15 提高 6.8 个百分点”并不矛盾——"
    "后者是在 $M=5$ 且 $T$ 更大的配置下测得的，那里每轮步长相对 $\\varepsilon$ 更小、饱和出现得更晚；"
    "但它提示 $T$ 的最优取值取决于 $M$、$\\alpha/\\varepsilon$ 与分辨率的组合，"
    "本文未对三者的交互做系统扫描，故不主张 $T=15$ 具有普适最优性。"
)
assert "{{TSCAN_TEXT}}" in s, "占位缺失"
s = s.replace("{{TSCAN_TEXT}}", txt, 1)
open(p, "w", encoding="utf-8", newline="").write(s)
print("left placeholders:", s.count("{{"))
